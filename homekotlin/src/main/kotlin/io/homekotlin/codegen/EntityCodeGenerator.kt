package io.homekotlin.codegen

import io.homekotlin.ha.HaState
import io.homekotlin.ha.HaStateStore
import java.io.File
import java.time.Instant

class EntityCodeGenerator(private val stateStore: HaStateStore) {

    fun generateCode(style: String = "objects", domain: String? = null): String {
        val allEntities = stateStore.allStates().values.sortedBy { it.entityId }
        val entities = if (!domain.isNullOrBlank()) {
            allEntities.filter { it.domain.equals(domain, ignoreCase = true) }
        } else {
            allEntities
        }
        val byDomain = entities.groupBy { it.domain }

        return when (style.lowercase()) {
            "constants" -> generateFlatConstants(byDomain, entities.size)
            "typed" -> generateTypedEntities(byDomain, entities.size)
            else -> generateGroupedObjects(byDomain, entities.size)
        }
    }

    private fun generateGroupedObjects(byDomain: Map<String, List<HaState>>, totalCount: Int): String {
        val sb = StringBuilder()
        sb.appendLine("package io.homekotlin.generated")
        sb.appendLine()
        sb.appendLine("// Auto-generated by HomeKotlin at ${Instant.now()}")
        sb.appendLine("// Discovered entities: $totalCount")
        sb.appendLine("// Copy & paste these objects directly into your automation files:")
        sb.appendLine()

        for ((domain, list) in byDomain.toSortedMap()) {
            val objectName = domain.toDomainObjectName()
            sb.appendLine("object $objectName {")
            for (item in list) {
                val constName = item.objectId.toConstantName()
                val friendlyComment = item.friendlyName.replace("\n", " ").trim()
                sb.appendLine("    /** $friendlyComment (State: ${item.state}) */")
                sb.appendLine("    const val $constName = \"${item.entityId}\"")
            }
            sb.appendLine("}")
            sb.appendLine()
        }
        return sb.toString()
    }

    private fun generateFlatConstants(byDomain: Map<String, List<HaState>>, totalCount: Int): String {
        val sb = StringBuilder()
        sb.appendLine("// Auto-generated by HomeKotlin at ${Instant.now()}")
        sb.appendLine("// Discovered entities: $totalCount")
        sb.appendLine()

        for ((domain, list) in byDomain.toSortedMap()) {
            val domainTitle = domain.replace('_', ' ').replaceFirstChar { it.uppercase() }
            sb.appendLine("// --- $domainTitle ---")
            for (item in list) {
                val constName = (domain + "_" + item.objectId).toConstantName()
                val friendlyComment = item.friendlyName.replace("\n", " ").trim()
                sb.appendLine("/** $friendlyComment (State: ${item.state}) */")
                sb.appendLine("const val $constName = \"${item.entityId}\"")
            }
            sb.appendLine()
        }
        return sb.toString()
    }

    private fun generateTypedEntities(byDomain: Map<String, List<HaState>>, totalCount: Int): String {
        val sb = StringBuilder()
        sb.appendLine("package io.homekotlin.generated")
        sb.appendLine()
        sb.appendLine("// Auto-generated by HomeKotlin at ${Instant.now()}")
        sb.appendLine("// Discovered entities: $totalCount")
        sb.appendLine()
        sb.appendLine("open class Entity(val entityId: String) : CharSequence by entityId {")
        sb.appendLine("    override fun toString(): String = entityId")
        sb.appendLine("}")
        sb.appendLine()
        sb.appendLine("class LightEntity(entityId: String) : Entity(entityId)")
        sb.appendLine("class SwitchEntity(entityId: String) : Entity(entityId)")
        sb.appendLine("class SensorEntity(entityId: String) : Entity(entityId)")
        sb.appendLine("class BinarySensorEntity(entityId: String) : Entity(entityId)")
        sb.appendLine("class ClimateEntity(entityId: String) : Entity(entityId)")
        sb.appendLine("class CoverEntity(entityId: String) : Entity(entityId)")
        sb.appendLine("class MediaPlayerEntity(entityId: String) : Entity(entityId)")
        sb.appendLine("class GenericEntity(entityId: String) : Entity(entityId)")
        sb.appendLine()
        sb.appendLine("object Entities {")

        for ((domain, list) in byDomain.toSortedMap()) {
            val domainClassName = domain.toPascalCase()
            val entityType = when (domain) {
                "light" -> "LightEntity"
                "switch" -> "SwitchEntity"
                "sensor" -> "SensorEntity"
                "binary_sensor" -> "BinarySensorEntity"
                "climate" -> "ClimateEntity"
                "cover" -> "CoverEntity"
                "media_player" -> "MediaPlayerEntity"
                else -> "GenericEntity"
            }

            sb.appendLine("    object $domainClassName {")
            for (item in list) {
                val propName = item.objectId.toCamelCase()
                val friendlyComment = item.friendlyName.replace("\n", " ").trim()
                sb.appendLine("        /** $friendlyComment (State: ${item.state}) */")
                sb.appendLine("        val $propName = $entityType(\"${item.entityId}\")")
            }
            sb.appendLine("    }")
            sb.appendLine()
        }

        sb.appendLine("}")
        return sb.toString()
    }

    fun generateToFile(outputFile: File, style: String = "typed", domain: String? = null): File {
        val code = generateCode(style, domain)
        outputFile.parentFile?.mkdirs()
        outputFile.writeText(code)
        return outputFile
    }

    private fun String.toDomainObjectName(): String {
        return when (this.lowercase()) {
            "light" -> "Lights"
            "switch" -> "Switches"
            "sensor" -> "Sensors"
            "binary_sensor" -> "BinarySensors"
            "climate" -> "Climate"
            "cover" -> "Covers"
            "media_player" -> "MediaPlayers"
            "scene" -> "Scenes"
            "automation" -> "Automations"
            else -> this.toPascalCase()
        }
    }

    private fun String.toConstantName(): String {
        val cleaned = this.replace('-', '_').replace('.', '_')
        val upper = cleaned.uppercase()
        val candidate = if (upper.firstOrNull()?.isDigit() == true) "_$upper" else upper
        return if (isKotlinKeyword(candidate.lowercase())) "`$candidate`" else candidate
    }

    private fun String.toCamelCase(): String {
        val parts = this.split('_', '-', '.')
        if (parts.isEmpty()) return "entity"
        val first = parts[0].replaceFirstChar { it.lowercase() }
        val rest = parts.drop(1).joinToString("") { part ->
            part.replaceFirstChar { it.uppercase() }
        }
        val candidate = "$first$rest"
        return if (candidate.firstOrNull()?.isDigit() == true || isKotlinKeyword(candidate)) {
            "`$candidate`"
        } else {
            candidate
        }
    }

    private fun String.toPascalCase(): String {
        return this.split('_', '-', '.')
            .joinToString("") { it.replaceFirstChar { ch -> ch.uppercase() } }
    }

    private fun isKotlinKeyword(str: String): Boolean {
        return str in setOf(
            "as", "break", "class", "continue", "do", "else", "false", "for", "fun",
            "if", "in", "interface", "is", "null", "object", "package", "return",
            "super", "this", "throw", "true", "try", "typealias", "val", "var", "when", "while"
        )
    }
}
