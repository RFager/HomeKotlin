class EntityCodeGenerator(private val stateStore: HaStateStore) {

    fun generateCode(style: String = "objects", domain: String? = null): String {
        val allEntities = stateStore.allStates().values.sortedBy { it.entityId }
        val entities = if (!domain.isNullOrBlank()) {
            allEntities.filter { it.domain.equals(domain, ignoreCase = true) }
        } else {
            allEntities
        }
        val byDomain = entities.groupBy { it.domain }

        return when (style.lowercase()) {
            "constants" -> generateFlatConstants(byDomain, entities.size)
            "typed" -> generateTypedEntities(byDomain, entities.size)
            else -> generateGroupedObjects(byDomain, entities.size)
        }
    }

    private fun generateGroupedObjects(byDomain: Map<String, List<HaState>>, totalCount: Int): String {
        val sb = StringBuilder()
        sb.appendLine("package io.homekotlin.generated")
        sb.appendLine()
        sb.appendLine("import io.homekotlin.ha.HaState")
        sb.appendLine("import io.homekotlin.ha.HaStateStore")
        sb.appendLine("import kotlinx.serialization.json.JsonElement")
        sb.appendLine("import kotlinx.serialization.json.JsonArray")
        sb.appendLine("import kotlinx.serialization.json.JsonPrimitive")
        sb.appendLine()
        sb.appendLine("// Auto-generated by HomeKotlin at ${Instant.now()}")
        sb.appendLine("// Discovered entities: $totalCount")
        sb.appendLine()

        generateClassHierarchy(sb)

        for ((domain, list) in byDomain.toSortedMap()) {
            val domainClassName = domain.toPascalCase()
            val entityType = getEntityTypeForDomain(domain)

            sb.appendLine("object $domainClassName {")
            for (item in list) {
                val constName = item.objectId.toConstantName()
                val propName = item.objectId.toCamelCase()
                val friendlyComment = item.friendlyName.replace("\n", " ").trim()
                val options = extractOptions(item)

                sb.appendLine("    /** $friendlyComment (State: ${item.state}) */")
                if (options.isNotEmpty()) {
                    val distinctOptions = mutableMapOf<String, String>()
                    for (opt in options) {
                        var cName = opt.toConstantName()
                        var counter = 1
                        val base = cName
                        while (distinctOptions.containsKey(cName)) {
                            cName = "${base}_${++counter}"
                        }
                        distinctOptions[cName] = opt
                    }
                    sb.appendLine("    val $constName = object : $entityType(\"${item.entityId}\") {")
                    for ((cName, optVal) in distinctOptions) {
                        val escaped = optVal.replace("\\", "\\\\").replace("\"", "\\\"")
                        sb.appendLine("        val $cName = \"$escaped\"")
                    }
                    val optionsList = options.joinToString(", ") { "\"${it.replace("\\", "\\\\").replace("\"", "\\\"")}\"" }
                    sb.appendLine("        val options = listOf($optionsList)")
                    sb.appendLine("    }")
                } else {
                    sb.appendLine("    val $constName = $entityType(\"${item.entityId}\")")
                }
                if (propName != constName) {
                    sb.appendLine("    val $propName = $constName")
                }
            }
            sb.appendLine("}")
            sb.appendLine()
        }

        // Plural domain aliases for developer convenience (e.g. Lights, Switches, BinarySensors)
        for ((domain, _) in byDomain.toSortedMap()) {
            val singular = domain.toPascalCase()
            val plural = domain.toDomainObjectName()
            if (plural != singular) {
                sb.appendLine("val $plural = $singular")
            }
        }
        sb.appendLine()

        // Root Entities registry object
        sb.appendLine("object Entities {")
        for ((domain, _) in byDomain.toSortedMap()) {
            val domainClassName = domain.toPascalCase()
            sb.appendLine("    val $domainClassName = io.homekotlin.generated.$domainClassName")
        }
        sb.appendLine("}")
        return sb.toString()
    }

    private fun generateTypedEntities(byDomain: Map<String, List<HaState>>, totalCount: Int): String {
        return generateGroupedObjects(byDomain, totalCount)
    }

    private fun generateFlatConstants(byDomain: Map<String, List<HaState>>, totalCount: Int): String {
        val sb = StringBuilder()
        sb.appendLine("package io.homekotlin.generated")
        sb.appendLine()
        sb.appendLine("import io.homekotlin.ha.HaState")
        sb.appendLine("import io.homekotlin.ha.HaStateStore")
        sb.appendLine("import kotlinx.serialization.json.JsonElement")
        sb.appendLine("import kotlinx.serialization.json.JsonArray")
        sb.appendLine("import kotlinx.serialization.json.JsonPrimitive")
        sb.appendLine()
        sb.appendLine("// Auto-generated by HomeKotlin at ${Instant.now()}")
        sb.appendLine("// Discovered entities: $totalCount")
        sb.appendLine()

        generateClassHierarchy(sb)

        for ((domain, list) in byDomain.toSortedMap()) {
            val domainTitle = domain.replace('_', ' ').replaceFirstChar { it.uppercase() }
            val entityType = getEntityTypeForDomain(domain)
            sb.appendLine("// --- $domainTitle ---")
            for (item in list) {
                val constName = (domain + "_" + item.objectId).toConstantName()
                val friendlyComment = item.friendlyName.replace("\n", " ").trim()
                sb.appendLine("/** $friendlyComment (State: ${item.state}) */")
                sb.appendLine("val $constName = $entityType(\"${item.entityId}\")")
            }
            sb.appendLine()
        }
        return sb.toString()
    }

    private fun generateClassHierarchy(sb: StringBuilder) {
        // Base Entity class
        sb.appendLine("""
open class Entity(val entityId: String) : CharSequence by entityId {
    override fun toString(): String = entityId
    open val state: EntityState get() = EntityState(entityId)
    val isOn: Boolean get() = state.isOn
    val isOff: Boolean get() = state.isOff
    val isUnavailable: Boolean get() = state.isUnavailable
    val isUnknown: Boolean get() = state.isUnknown

    val UNAVAILABLE get() = "unavailable"
    val UNKNOWN get() = "unknown"

    companion object {
        var stateStore: HaStateStore? = null
        const val UNAVAILABLE = "unavailable"
        const val UNKNOWN = "unknown"
    }
}

open class EntityState(val entityId: String) : CharSequence {
    val current: HaState? get() = Entity.stateStore?.get(entityId)
    val raw: String get() = current?.state ?: "unknown"
    val value: String get() = raw
    val attributes: Map<String, JsonElement> get() = current?.attributes ?: emptyMap()

    val isOn: Boolean get() = raw.equals("on", ignoreCase = true)
    val isOff: Boolean get() = raw.equals("off", ignoreCase = true)
    val isUnavailable: Boolean get() = raw.equals("unavailable", ignoreCase = true) || raw.equals("unknown", ignoreCase = true)
    val isUnknown: Boolean get() = raw.equals("unknown", ignoreCase = true)

    fun isState(expected: String): Boolean = raw.equals(expected, ignoreCase = true)

    val UNAVAILABLE = "unavailable"
    val UNKNOWN = "unknown"
    open val availableStates: List<String> get() = listOf(UNAVAILABLE, UNKNOWN)

    override val length: Int get() = raw.length
    override fun get(index: Int): Char = raw[index]
    override fun subSequence(startIndex: Int, endIndex: Int): CharSequence = raw.subSequence(startIndex, endIndex)
    override fun toString(): String = raw
    override fun equals(other: Any?): Boolean {
        if (other is CharSequence) return raw.equals(other.toString(), ignoreCase = true)
        return super.equals(other)
    }
    override fun hashCode(): Int = raw.lowercase().hashCode()
}

